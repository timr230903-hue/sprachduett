def check_roman(text, label):
    for ch in unicodedata.normalize("NFD", text):
        if ch in " -'" or ch in MARKS:
            continue
        name = unicodedata.name(ch, "")
        if "LATIN" not in name:
            raise SystemExit(f"Umschrift {label!r} hat {ch!r} ({name})")


def check_thai(text, label):
    if not any(0x0E00 <= ord(ch) <= 0x0E7F for ch in text):
        raise SystemExit(f"Kein Thai in {label}")
    for ch in text:
        if "LATIN" in unicodedata.name(ch, ""):
            raise SystemExit(f"Latein in Thai {label}: {text}")


def main():
    phrases = [item for group in TOPICS for item in group["items"]]
    ids = [item["id"] for item in phrases]
    if len(ids) != len(set(ids)):
        raise SystemExit("doppelte Phrase-ID")
    if len(phrases) < 300:
        raise SystemExit(f"nur {len(phrases)} Phrasen")
    line_ids = []
    for group in SCENES:
        roles = {row["role"] for row in group["lines"]}
        if roles != {"a", "b"}:
            raise SystemExit(f"Rollen in {group['id']}")
        if len(group["lines"]) < 6:
            raise SystemExit(f"zu kurz: {group['id']}")
        for row in group["lines"]:
            line_ids.append(row["id"])
            check_thai(row["thai"], row["id"])
            check_roman(row["roman"], row["id"])
    if len(line_ids) != len(set(line_ids)):
        raise SystemExit("doppelte Zeilen-ID")
    if len(SCENES) < 12:
        raise SystemExit("zu wenige Szenen")
    for item in phrases:
        check_thai(item["thai"], item["id"])
        check_roman(item["roman"], item["id"])
    for tone in TONES:
        check_thai(tone["exampleThai"], tone["id"])
        check_roman(tone["exampleRoman"], tone["id"])
        check_roman(tone["roman"], tone["id"] + " name")
    catalog = {
        "language": "th",
        "title": "Thai",
        "tones": TONES,
        "topics": TOPICS,
        "scenes": SCENES,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(phrases)} Phrasen, {len(SCENES)} Szenen, {len(line_ids)} Zeilen -> {OUT}")


if __name__ == "__main__":
    main()
